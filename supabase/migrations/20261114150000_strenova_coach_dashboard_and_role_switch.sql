-- Strenova: safe role switching, coach access to connected athlete profiles/schedules,
-- and coach-managed nutrition targets with immutable change history.
begin;

create or replace function public.set_my_account_role(p_role text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_code text;
begin
  if v_uid is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if p_role not in ('athlete','coach') then
    raise exception 'Unsupported account type' using errcode = '22023';
  end if;
  if exists (
    select 1 from public.user_roles r
    where r.user_id = v_uid and r.role = 'admin'
  ) then
    raise exception 'Administrator role cannot be changed here' using errcode = '42501';
  end if;

  delete from public.user_roles
  where user_id = v_uid and role in ('athlete','coach');
  insert into public.user_roles(user_id,role) values (v_uid,p_role);

  if p_role = 'coach' then
    insert into public.gt_user_roles(user_id,role)
    values (v_uid,'coach')
    on conflict (user_id) do update set role = excluded.role;

    v_code := 'COACH-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));
    insert into public.coach_profiles(user_id,specialization,experience_years,bio,coach_code)
    values (v_uid,'General fitness',0,'',v_code)
    on conflict (user_id) do nothing;

    insert into public.coach_invites(coach_id,invite_code)
    select cp.user_id,cp.coach_code
    from public.coach_profiles cp
    where cp.user_id = v_uid
    on conflict (invite_code) do nothing;
  else
    delete from public.gt_user_roles where user_id = v_uid;
  end if;

  update public.user_profiles
  set profile = jsonb_set(coalesce(profile,'{}'::jsonb),'{accountType}',to_jsonb(p_role),true),
      updated_at = now()
  where user_id = v_uid;

  return jsonb_build_object('success',true,'role',p_role);
end;
$$;
revoke all on function public.set_my_account_role(text) from public,anon;
grant execute on function public.set_my_account_role(text) to authenticated;

-- Connected coaches may read only the profiles of their active athletes.
drop policy if exists user_profiles_read_self_or_admin on public.user_profiles;
create policy user_profiles_read_self_coach_or_admin
on public.user_profiles for select to authenticated
using (
  user_id = (select auth.uid())
  or private.is_active_coach_for_athlete(user_id)
  or private.is_admin()
);

-- The athlete keeps ownership; the active coach receives narrowly scoped schedule access.
drop policy if exists workout_schedule_insert_active_coach on public.workout_schedule;
create policy workout_schedule_insert_active_coach
on public.workout_schedule for insert to authenticated
with check (private.is_active_coach_for_athlete(user_id));

drop policy if exists workout_schedule_update_active_coach on public.workout_schedule;
create policy workout_schedule_update_active_coach
on public.workout_schedule for update to authenticated
using (private.is_active_coach_for_athlete(user_id))
with check (private.is_active_coach_for_athlete(user_id));

drop policy if exists workout_schedule_delete_active_coach on public.workout_schedule;
create policy workout_schedule_delete_active_coach
on public.workout_schedule for delete to authenticated
using (private.is_active_coach_for_athlete(user_id));

create table if not exists public.athlete_nutrition_targets (
  athlete_id uuid primary key references auth.users(id) on delete cascade,
  calories_kcal integer check (calories_kcal is null or calories_kcal between 0 and 20000),
  protein_g numeric(7,2) check (protein_g is null or protein_g between 0 and 2000),
  fat_g numeric(7,2) check (fat_g is null or fat_g between 0 and 2000),
  carbs_g numeric(7,2) check (carbs_g is null or carbs_g between 0 and 3000),
  water_ml integer check (water_ml is null or water_ml between 0 and 20000),
  notes text not null default '' check (char_length(notes) <= 1000),
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.athlete_nutrition_history (
  id bigint generated by default as identity primary key,
  athlete_id uuid not null references auth.users(id) on delete cascade,
  calories_kcal integer,
  protein_g numeric(7,2),
  fat_g numeric(7,2),
  carbs_g numeric(7,2),
  water_ml integer,
  notes text not null default '',
  changed_by uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now()
);

alter table public.athlete_nutrition_targets enable row level security;
alter table public.athlete_nutrition_history enable row level security;

