create or replace function private.stamp_nutrition_target_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end;
$$;

create or replace function private.audit_nutrition_target_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if TG_OP = 'UPDATE'
     and row(new.calories_kcal,new.protein_g,new.fat_g,new.carbs_g,new.water_ml,new.notes)
         is not distinct from
         row(old.calories_kcal,old.protein_g,old.fat_g,old.carbs_g,old.water_ml,old.notes) then
    return new;
  end if;

  insert into public.athlete_nutrition_history(
    athlete_id,calories_kcal,protein_g,fat_g,carbs_g,water_ml,notes,changed_by
  ) values (
    new.athlete_id,new.calories_kcal,new.protein_g,new.fat_g,new.carbs_g,
    new.water_ml,new.notes,coalesce(auth.uid(),new.updated_by)
  );
  return new;
end;
$$;

drop trigger if exists athlete_nutrition_targets_stamp on public.athlete_nutrition_targets;
create trigger athlete_nutrition_targets_stamp
before insert or update on public.athlete_nutrition_targets
for each row execute function private.stamp_nutrition_target_change();

drop trigger if exists athlete_nutrition_targets_audit on public.athlete_nutrition_targets;
create trigger athlete_nutrition_targets_audit
after insert or update on public.athlete_nutrition_targets
for each row execute function private.audit_nutrition_target_change();

grant select,insert,update,delete on public.athlete_nutrition_targets to authenticated;
grant select on public.athlete_nutrition_history to authenticated;
grant usage,select on sequence public.athlete_nutrition_history_id_seq to authenticated;

create index if not exists athlete_coach_relationships_coach_status_idx
