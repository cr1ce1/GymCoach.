-- STRENOVA Supabase schema
-- Idempotent setup: existing tables are not duplicated and existing user rows are not deleted.
-- Review the live database before applying if tables already exist with a different structure.

create table if not exists public.user_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  profile jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.workout_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  completed_exercises integer not null default 0,
  minutes integer not null default 0,
  details jsonb not null default '{}'::jsonb,
  client_record_id text,
  created_at timestamptz not null default now()
);
alter table public.workout_logs add column if not exists client_record_id text;
create unique index if not exists workout_logs_user_client_record_uidx
  on public.workout_logs(user_id, client_record_id);

create table if not exists public.workout_schedule (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  scheduled_for date not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.workout_templates (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  details jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  constraint workout_templates_user_name_key unique (user_id, name)
);

create table if not exists public.workout_drafts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  title text not null default 'Workout',
  details jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.user_custom_exercises (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  en_name text,
  category text not null default 'Власні',
  muscles text,
  instructions text,
  mistakes text,
  aliases jsonb not null default '[]'::jsonb,
  equipment jsonb not null default '[]'::jsonb,
  training_location text not null default 'all',
  difficulty text,
  video_url text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_custom_exercises_user_name_key unique (user_id, name)
);

create table if not exists public.gt_subscriptions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  status text not null default 'inactive',
  plan text not null default 'free',
  starts_at timestamptz,
  expires_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.gt_user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user',
  updated_at timestamptz not null default now()
);

create table if not exists public.gt_coach_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  sender_name text not null default '',
  sender_email text not null default '',
  body text not null,
  created_at timestamptz not null default now()
);
create index if not exists gt_coach_messages_user_created_idx
  on public.gt_coach_messages(user_id, created_at);

alter table public.user_profiles enable row level security;
alter table public.workout_logs enable row level security;
alter table public.workout_schedule enable row level security;
alter table public.workout_templates enable row level security;
alter table public.workout_drafts enable row level security;
alter table public.user_custom_exercises enable row level security;
alter table public.gt_subscriptions enable row level security;
alter table public.gt_user_roles enable row level security;
alter table public.gt_coach_messages enable row level security;

create or replace function public.is_strenova_coach()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.gt_user_roles
    where user_id = auth.uid() and role = 'coach'
  );
$$;
grant execute on function public.is_strenova_coach() to authenticated;

drop policy if exists "Users manage own profile" on public.user_profiles;
create policy "Users manage own profile" on public.user_profiles
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own workouts" on public.workout_logs;
create policy "Users manage own workouts" on public.workout_logs
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own schedule" on public.workout_schedule;
create policy "Users manage own schedule" on public.workout_schedule
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own templates" on public.workout_templates;
create policy "Users manage own templates" on public.workout_templates
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own drafts" on public.workout_drafts;
create policy "Users manage own drafts" on public.workout_drafts
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own custom exercises" on public.user_custom_exercises;
create policy "Users manage own custom exercises" on public.user_custom_exercises
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users read own subscription" on public.gt_subscriptions;
create policy "Users read own subscription" on public.gt_subscriptions
  for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Users read own role" on public.gt_user_roles;
create policy "Users read own role" on public.gt_user_roles
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists "Members and coaches read chat threads" on public.gt_coach_messages;
create policy "Members and coaches read chat threads" on public.gt_coach_messages
  for select to authenticated using (auth.uid() = user_id or public.is_strenova_coach());
drop policy if exists "Members and coaches send chat messages" on public.gt_coach_messages;
create policy "Members and coaches send chat messages" on public.gt_coach_messages
  for insert to authenticated
  with check (
    sender_id = auth.uid()
    and (user_id = auth.uid() or public.is_strenova_coach())
  );

grant select, insert, update, delete on public.user_profiles to authenticated;
grant select, insert, update, delete on public.workout_logs to authenticated;
grant select, insert, update, delete on public.workout_schedule to authenticated;
grant select, insert, update, delete on public.workout_templates to authenticated;
grant select, insert, update, delete on public.workout_drafts to authenticated;
grant select, insert, update, delete on public.user_custom_exercises to authenticated;
grant select on public.gt_subscriptions to authenticated;
grant select on public.gt_user_roles to authenticated;
grant select, insert on public.gt_coach_messages to authenticated;

notify pgrst, 'reload schema';
